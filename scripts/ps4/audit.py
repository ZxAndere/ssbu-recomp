"""Inventory platform dependencies in tracked source files; never inspect dumps/keys.

This is a lexical review aid, not a whole-program call graph. Comments also match.
"""
import argparse
from collections import Counter
import csv
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
AREAS = ("runtime", "graphics_sdk", "tools/lifter", "tools/port", "scripts", "tests", "fighter_sdk")
PATTERNS = {
    "Win32": r"windows\.h|\b(?:HMODULE|HANDLE|HWND|DWORD|WINAPI|WIN32|_WIN32)\b|\b(?:GetModuleHandle|GetModuleFileName|GetEnvironmentVariable|GetLastError|SetUnhandledExceptionFilter|AddVectoredExceptionHandler|GetCurrentThreadId|GetCurrentProcessId)\w*",
    "DLL/ABI": r"\b(?:LoadLibrary\w*|FreeLibrary|GetProcAddress|__declspec|__stdcall|__fastcall|__declspec|lld-link|ucrtbase|ntdll)\b|\.dll\b|\.lib\b|/dll\b",
    "Memory": r"\b(?:VirtualAlloc\w*|VirtualFree\w*|VirtualProtect\w*|VirtualQuery\w*|MEM_RESERVE|MEM_COMMIT|PAGE_READWRITE|PAGE_NOACCESS|_aligned_malloc|_aligned_free)\b",
    "Threads/sync": r"\b(?:CreateThread|CreateFiber\w*|ConvertThreadToFiber\w*|SwitchToFiber|DeleteFiber|Fls\w*|Tls\w*|SRWLOCK\w*|CRITICAL_SECTION|CONDITION_VARIABLE|InitializeCriticalSection\w*|EnterCriticalSection|LeaveCriticalSection|WaitFor\w*|Wake\w*|CreateEvent\w*|SetEvent|ResetEvent|Interlocked\w*|AcquireSRWLock\w*|ReleaseSRWLock\w*|SetThread\w*|TerminateThread|CloseHandle)\b",
    "Timing": r"\b(?:QueryPerformanceCounter|QueryPerformanceFrequency|Sleep|GetTickCount\w*|CreateWaitableTimer\w*|SetWaitableTimer\w*|timeBeginPeriod|timeGetTime)\b",
    "Filesystem": r"\b(?:CreateFile\w*|CreateFileMapping\w*|MapViewOfFile\w*|UnmapViewOfFile|ReadFile|WriteFile|SetFilePointer\w*|GetFileSize\w*|FindFirstFile\w*|FindNextFile\w*|FindClose|GetFileAttributes\w*|CreateDirectory\w*|GetFullPathName\w*|_fseeki64|_ftelli64|_mkdir|_stat64|MAX_PATH)\b",
    "SDL3/input": r"\bSDL_\w+|SDL3|[Xx][Ii]nput\w*",
    "Graphics": r"\bvk\w+|\bVk\w+|VK_KHR_win32_surface|VK_USE_PLATFORM_WIN32_KHR|\bwgl\w+|\bHDC\b|vulkan-1|opengl32|glslang|D3DKMT\w*",
    "Media Foundation": r"\b(?:MFStartup|MFShutdown|MFCreate\w*|IMF\w+|CoInitialize\w*|CoCreateInstance|CoTaskMemFree|HRESULT|GUID)\b|mfapi\.h|mfidl\.h|mfreadwrite|mfuuid|ole32",
    "Audio": r"\b(?:waveOut\w*|WAVEHDR|WAVEFORMATEX|HWAVEOUT)\b|mmsystem\.h|winmm|opus.*\.dll",
    "Network": r"winsock\w*|ws2_32|\b(?:WSA\w*|SOCKET|closesocket|ioctlsocket|WinHttp\w*|InetPton\w*)\b",
    "Windows build/tools": r"clang\.exe|link\.exe|vswhere|MSVC|Visual Studio|Windows SDK|\.bat\b|powershell|winreg|os\.name\s*==\s*['\"]nt|sys\.platform.*win32",
}
COMPILED = {key: re.compile(value, re.I if key == "Windows build/tools" else 0)
            for key, value in PATTERNS.items()}
TEXT_EXTENSIONS = {".c", ".cpp", ".h", ".inc", ".py", ".ps1", ".bat", ".sh", ".md", ".def", ".json", ".ini", ".txt"}


def collect(root=ROOT):
    tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=root).decode().split("\0")
    counts, rows = Counter(), []
    for name in sorted(set(tracked)):
        if not name or not any(name.startswith(area + "/") for area in AREAS):
            continue
        path = root / name
        if path.suffix.lower() not in TEXT_EXTENSIONS or not path.is_file():
            continue
        area = next(area for area in AREAS if name.startswith(area + "/"))
        counts[area] += 1
        for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for category, pattern in COMPILED.items():
                matches = sorted(set(m.group(0) for m in pattern.finditer(line)))
                if matches:
                    rows.append((name, number, category, ", ".join(matches), line.strip()[:240].rstrip()))
    return counts, rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "docs/ps4")
    args = parser.parse_args()
    counts, rows = collect()
    args.out.mkdir(parents=True, exist_ok=True)
    with (args.out / "dependencies.tsv").open("w", encoding="utf-8", newline="") as out:
        writer = csv.writer(out, delimiter="\t", lineterminator="\n")
        writer.writerow(("file", "line", "category", "symbols", "source"))
        writer.writerows(rows)
    report = ["# Platform dependency inventory", "", "Generated by `python scripts/ps4/audit.py` from tracked text files.",
              "Lexical matches include comments, tests, strings and platform guards; counts are not call counts.", "",
              "| Area | Text files scanned | Status |", "|---|---:|---|"]
    for area in AREAS:
        report.append(f"| {area}/ | {counts[area]} | {'present' if (ROOT / area).is_dir() else 'absent'} |")
    report += ["", "| Category | Matching lines | Files |", "|---|---:|---:|"]
    for category in COMPILED:
        group = [r for r in rows if r[2] == category]
        report.append(f"| {category} | {len(group)} | {len({r[0] for r in group})} |")
    report += ["", "Full file/line evidence: [dependencies.tsv](dependencies.tsv).", ""]
    (args.out / "inventory.md").write_text("\n".join(report), encoding="utf-8")
    print(f"Scanned {sum(counts.values())} tracked text files; {len(rows)} dependency rows.")


if __name__ == "__main__":
    main()
